class quad_max;
    rand bit [3:0] m[4][4];

    constraint c_bound { foreach (m[i, j]) m[i][j] <= 5 + 3 * ((i / 2) * 2 + j / 2); }
    constraint c_hit {
        m[0][0] == 5  || m[0][1] == 5  || m[1][0] == 5  || m[1][1] == 5;
        m[0][2] == 8  || m[0][3] == 8  || m[1][2] == 8  || m[1][3] == 8;
        m[2][0] == 11 || m[2][1] == 11 || m[3][0] == 11 || m[3][1] == 11;
        m[2][2] == 14 || m[2][3] == 14 || m[3][2] == 14 || m[3][3] == 14;
    }
endclass
