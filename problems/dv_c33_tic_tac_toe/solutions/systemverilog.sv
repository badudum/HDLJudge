class ttt;
    rand bit [1:0] b[3][3];     // 0 = empty, 1 = X, 2 = O

    constraint c_cell { foreach (b[i, j]) b[i][j] inside {[0:2]}; }
    constraint c_count {
        int'(b[0][0] == 1) + (b[0][1] == 1) + (b[0][2] == 1) + (b[1][0] == 1) + (b[1][1] == 1) + (b[1][2] == 1) +
        (b[2][0] == 1) + (b[2][1] == 1) + (b[2][2] == 1) ==
        int'(b[0][0] == 2) + (b[0][1] == 2) + (b[0][2] == 2) + (b[1][0] == 2) + (b[1][1] == 2) + (b[1][2] == 2) +
        (b[2][0] == 2) + (b[2][1] == 2) + (b[2][2] == 2) + 1;
    }
    constraint c_xwin {
        (b[0][0] == 1 && b[0][1] == 1 && b[0][2] == 1) || (b[1][0] == 1 && b[1][1] == 1 && b[1][2] == 1) ||
        (b[2][0] == 1 && b[2][1] == 1 && b[2][2] == 1) || (b[0][0] == 1 && b[1][0] == 1 && b[2][0] == 1) ||
        (b[0][1] == 1 && b[1][1] == 1 && b[2][1] == 1) || (b[0][2] == 1 && b[1][2] == 1 && b[2][2] == 1) ||
        (b[0][0] == 1 && b[1][1] == 1 && b[2][2] == 1) || (b[0][2] == 1 && b[1][1] == 1 && b[2][0] == 1);
    }
    constraint c_onowin {
        !(b[0][0] == 2 && b[0][1] == 2 && b[0][2] == 2) && !(b[1][0] == 2 && b[1][1] == 2 && b[1][2] == 2) &&
        !(b[2][0] == 2 && b[2][1] == 2 && b[2][2] == 2) && !(b[0][0] == 2 && b[1][0] == 2 && b[2][0] == 2) &&
        !(b[0][1] == 2 && b[1][1] == 2 && b[2][1] == 2) && !(b[0][2] == 2 && b[1][2] == 2 && b[2][2] == 2) &&
        !(b[0][0] == 2 && b[1][1] == 2 && b[2][2] == 2) && !(b[0][2] == 2 && b[1][1] == 2 && b[2][0] == 2);
    }
endclass
